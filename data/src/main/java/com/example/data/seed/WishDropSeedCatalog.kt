  fun generatePriceHistoryForProducts(products: List<ProductEntity>): List<PriceHistoryEntity> {
    val now = System.currentTimeMillis()
    val history = mutableListOf<PriceHistoryEntity>()
    val dayOffsets = listOf(420, 360, 300, 240, 180, 135, 90, 60, 45, 30, 21, 14, 7, 3, 0)
    products.forEachIndexed { pIndex, product ->
      val base = product.originalPriceHuf.coerceAtLeast(product.currentPriceHuf)
      dayOffsets.forEachIndexed { idx, daysAgo ->
        val price =
          when {
            daysAgo == 0 -> product.currentPriceHuf
            daysAgo <= 7 -> ((product.currentPriceHuf + base) / 2.0).roundToInt()
            else -> {
              val wave = sin((idx + pIndex) * 0.85) * 0.045
              ((base * (1.0 + wave)) / 100.0).roundToInt() * 100
            }
          }
        history.add(
          PriceHistoryEntity(
            productId = product.id,
            timestampMillis = now - daysAgo * DAY_MS,
            priceHuf = price,
            storeName = product.store,
          )
        )
      }
    }
    return history
  }
