  fun buildProductTagRefs(products: List<ProductEntity>): List<ProductTagCrossRefEntity> =
    products.flatMap { product ->
      val tags =
        runCatching { json.decodeFromString<List<String>>(product.tagsJson) }
          .getOrDefault(emptyList())
      tags.map { tag -> ProductTagCrossRefEntity(productId = product.id, tagName = tag) }
    }

  private fun buildProduct(
    id: String,
    title: String,
    store: String,
    currentPrice: Int,
    originalPrice: Int,
    priceChangePercent: Int,
    savingsHuf: Int,
    imageKey: String,
    sourceUrl: String = "",
    barcode: String = "",
    categories: List<String>,
    tags: List<String>,
    recipientId: String?,
    recipientName: String?,
    recipientConfidence: Int,
    sharedListId: String? = null,
    hiddenFromMemberId: String? = null,
    collectionName: String,
    isPurchased: Boolean = false,
    isFeaturedDeal: Boolean = false,
    createdOffsetDays: Int,
    alternatives: List<AlternativeProduct> = emptyList(),
    offers: List<StoreOffer> = emptyList(),
  ): ProductEntity {
    val resolvedOffers =
      offers.ifEmpty {
        listOf(
          StoreOffer(store, currentPrice, "In stock • 1-2 business days", true, true),
          StoreOffer("Alza", (currentPrice * 1.05).roundToInt(), "AlzaBox pickup", true, false),
          StoreOffer("MediaMarkt", (currentPrice * 1.09).roundToInt(), "Store pickup", true, false),
        )
      }
    return ProductEntity(
      id = id,
      title = title,
      store = store,
      currentPriceHuf = currentPrice,
      originalPriceHuf = originalPrice,
      priceChangePercent = priceChangePercent,
      savingsHuf = savingsHuf,
      imageKey = imageKey,
      sourceUrl = sourceUrl,
      barcode = barcode,
      categoriesJson = json.encodeToString(categories),
      tagsJson = json.encodeToString(tags),
      recipientId = recipientId,
      recipientName = recipientName,
      recipientConfidence = recipientConfidence,
      wishlistId = "wl_${collectionName.lowercase()}",
      sharedListId = sharedListId,
      hiddenFromMemberId = hiddenFromMemberId,
      collectionName = collectionName,
      isPurchased = isPurchased,
      isArchived = false,
      isPriceAlertEnabled = true,
      isFeaturedDeal = isFeaturedDeal,
      createdAtMillis = BASE_NOW_MS - createdOffsetDays * DAY_MS,
      alternativesJson = json.encodeToString(alternatives),
      storeOffersJson = json.encodeToString(resolvedOffers),
    )
  }

